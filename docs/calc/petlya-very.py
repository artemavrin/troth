import math
STEPS_YEAR = 8640          # шагов физики в мировом году (§3)
# §6 утверждает: без гейта ожидания слух за 2 года становится законом.
steps2 = 2 * STEPS_YEAR
for lo, hi in ((0.05, 0.95), (0.20, 0.95)):
    g = (hi/lo) ** (1/steps2)
    print(f"{lo:.0%}→{hi:.0%} за 2 года: достаточно усиления {(g-1)*100:.4f}% за шаг физики")

print()
# Условие устойчивости: усиление за год не должно пережить годовое затухание
for d in (0.95, 0.90, 0.70, 0.50):
    g_max = d ** (-1/STEPS_YEAR)
    print(f"затухание {1-d:.0%}/год ⇒ допустимое усиление ≤ {(g_max-1)*100:.5f}% за шаг — окно в {(g_max-1)*1e6:.1f} ppm")

print()
# Если затухание применять каждый шаг с той же годовой величиной — окно то же,
# но управляемость другая: сравним время полураспада
for d in (0.95, 0.90, 0.70, 0.50):
    hl_years = math.log(0.5)/math.log(d)
    print(f"затухание {1-d:.0%}/год ⇒ период полураспада {hl_years:.1f} мировых лет = {hl_years*2.5:.1f} реальных суток")
