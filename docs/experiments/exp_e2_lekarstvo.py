"""
Эксперимент E2 — что на самом деле возвращает выбор стратегии.

E показал: «подтверждает известное» дешевле в 200 раз за сбывшееся шептание,
а правка «репутация с весом натяга» ничего не меняет, потому что репутация —
отношение, и вес сокращается.

Причина дисбаланса видна из формулы: цена растёт с натягом как (1+2t) = ×3,
а шанс сбыться падает как 93%→3% = ×31. Издержка выросла втрое, риск — в
тридцать раз. Значит лечение не в цене, а в НАГРАДЕ: за натяг ничего не платят.
"""
import numpy as np

BASE, K = 100.0, 2.0
def p_fulfil(t): return 0.90 * (1.0 - t) ** 1.5 + 0.03
def price(t):    return BASE * (1.0 + K * t)

STRATS = [0.0, 0.25, 0.5, 0.75, 1.0]
NAMES = ["подтверждает известное", "правдоподобно", "неожиданно",
         "противоречит виденному", "против общего знания"]

print("="*78)
print("Во сколько раз награда за сбывшееся должна расти с натягом ради безразличия")
print("="*78)
c0 = price(0.0) / p_fulfil(0.0)
print(f"{'натяг':>8} {'цена':>8} {'шанс':>8} {'★/сбывшееся':>14} {'нужна награда':>16}")
print("-"*78)
for t, nm in zip(STRATS, NAMES):
    cph = price(t) / p_fulfil(t)
    print(f"{t:>8.2f} {price(t):>8.0f} {p_fulfil(t):>8.0%} {cph:>14.0f} {cph/c0:>15.1f}×")

print()
print("="*78)
print("Проверка: даём награде расти как (1+2t)^n и смотрим, где выбор оживает")
print("="*78)
print(f"{'показатель n':>14} " + "".join(f"{nm.split()[0][:11]:>13}" for nm in NAMES))
print(f"{'':>14} " + "".join(f"{'ценность/★':>13}" for _ in NAMES))
print("-"*78)
best_n = None
for n in (0, 1, 2, 3, 3.1, 4):
    vals = []
    for t in STRATS:
        value = (1.0 + K * t) ** n          # награда за сбывшееся
        vals.append(value * p_fulfil(t) / price(t))   # ценность на звезду
    spread = max(vals) / min(vals)
    row = "".join(f"{v:>13.3f}" for v in vals)
    mark = ""
    if spread < 2.0 and best_n is None:
        best_n = n; mark = "  ← выбор живой (разброс < 2×)"
    print(f"{n:>14} {row}{mark}")
    if n == 0:
        print(f"{'':>14}   (n=0 — это и есть формула документа: разброс " f"{spread:.0f}×)")

print()
print("="*78)
print("Вывод")
print("="*78)
print(f"""
Чтобы «против общего знания» перестало быть доминируемым, сбывшееся шептание
против течения должно приносить примерно в {price(1.0)/p_fulfil(1.0)/c0:.0f} раз больше, чем сбывшееся
по течению. В формуле §5 натяг стоит ТОЛЬКО в цене — то есть игрок платит за
риск, но за успех не получает ничего сверх обычного. Это не баланс, это налог.

Лечится не множителем цены и не весом в репутации (E показал, что второе —
пустышка), а третьей величиной, которой в документе нет: НАГРАДОЙ за натяг.
Кандидаты — сила эффекта на мир, отдельная шкала славы, доля в летописи.
""")
